"""Generate TS contracts from the Pydantic result schema (no duplicate hand-written types)."""

from pathlib import Path

from baseline_lab.contracts import Result

schema = Result.model_json_schema()


def ts(s):
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "enum" in s:
        return " | ".join(repr(x) for x in s["enum"])
    if "const" in s:
        return repr(s["const"])
    if "anyOf" in s:
        return " | ".join(ts(x) for x in s["anyOf"])
    t = s.get("type")
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(ts(x) for x in s["prefixItems"]) + "]"
        return "(" + ts(s.get("items", {})) + ")[]"
    if t == "object":
        if "properties" in s:
            return "{" + "; ".join(k + ": " + ts(v) for k, v in s["properties"].items()) + "}"
        return "Record<string, any>"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(t, "any")


lines = ["// Generated by scripts/generate-types.py; do not edit."]
for name, obj in {**schema.get("$defs", {}), "Analysis": schema}.items():
    props = ";\n".join("  " + k + ": " + ts(v) for k, v in obj["properties"].items())
    lines.append("export interface " + name + " {\n" + props + "\n}")
Path("apps/web/src/contracts.ts").write_text("\n".join(lines) + "\n")
